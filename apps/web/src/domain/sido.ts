export function sidoOf(name: string): string | null {
  const n = name.replace(/\s+/g, '');
  // 광주(전남) ↔ 경기 광주처럼 겹치는 이름은 앞에 적힌 시도를 먼저 본다
  for (const [sido, words] of Object.entries(CITIES))
    if (words.some((w) => n.startsWith(w))) return sido;
  for (const [sido, words] of Object.entries(CITIES))
    if (words.some((w) => n.includes(w))) return sido;
  return null;
}
