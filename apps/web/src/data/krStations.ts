/** 예약 칩 이름 → 노선 글자 (칩이 없거나 모르면 기차역 전체) */
const CHIP_LINE: Record<string, string> = {
  KTX: 'K',
  SRT: 'S',
  ITX: 'I',
  무궁화호: 'M',
  공항철도: 'A',
  고속버스: 'E',
  시외버스: 'C',
  공항버스: 'P',
};

/** 칩·도시 이름으로 거른 목록 (도시 이름은 시·도·시군·역 이름 어디든) */
export function krStationsFor(chip: string, cityQuery: string): KrStation[] {
  const line = CHIP_LINE[chip.trim()];
  const q = cityQuery.trim();
  return KR_STATIONS.filter(
    (s) =>
      (line ? s.lines.includes(line) : /[KSIMA]/.test(s.lines)) &&
      (!q || s.city.includes(q) || s.region.includes(q) || s.name.includes(q)),
  );
}

/** 해외 역 찾기 종류: 칩 이름으로 지하철·버스·기차 */
export function stationKindOf(chip: string): 'train' | 'subway' | 'bus' {
  if (/버스|bus|트롤리|셔틀/i.test(chip)) return 'bus';
  if (/지하철|메트로|metro|MRT|BTS|LRT|MTR|U반|S반|RER|튜브|트램|모노레일/i.test(chip))
    return 'subway';
  return 'train';
}
