const toRad = (d: number) => (d * Math.PI) / 180;
function km(a: { lat: number; lng: number }, b: { lat: number; lng: number }): number {
  const h =
    Math.sin(toRad(b.lat - a.lat) / 2) ** 2 +
    Math.cos(toRad(a.lat)) * Math.cos(toRad(b.lat)) * Math.sin(toRad(b.lng - a.lng) / 2) ** 2;
  return 12_742 * Math.asin(Math.sqrt(h));
}

const norm = (s: string) => s.toLowerCase().replace(/\s+/g, ' ').trim();

/** 여행 목적지 → 도시 정보 (좌표가 반경 안이면, 좌표가 없으면 이름으로). 없으면 null → 나라 대표 정보 */
export function cityLocalFor(dest: {
  name: string;
  countryCode?: string | undefined;
  coords?: { lat: number; lng: number } | undefined;
}): CityLocal | null {
  const same = CITY_LOCAL.filter((c) => !dest.countryCode || c.country === dest.countryCode);
  if (dest.coords) {
    const near = same
      .map((c) => ({ c, d: km(dest.coords!, c.center) }))
      .filter((x) => x.d <= x.c.radiusKm)
      .sort((a, b) => a.d - b.d)[0];
    if (near) return near.c;
  }
  const name = norm(dest.name);
  return same.find((c) => c.aliases.some((a) => name.includes(norm(a)))) ?? null;
}
